func TestPostgresIntrospectionIntegration(t *testing.T) {
	if testing.Short() {
		t.Skip("Skipping integration test in short mode")
	}

	ctx := context.Background()

	// 1. Setup Postgres Testcontainer
	pgContainer, err := postgres.Run(ctx,
		"docker.io/postgres:16-alpine",
		postgres.WithDatabase("testdb"),
		postgres.WithUsername("testuser"),
		postgres.WithPassword("testpass"),
		testcontainers.WithWaitStrategy(
			wait.ForLog("database system is ready to accept connections").
				WithOccurrence(2).
				WithStartupTimeout(60*time.Second)),
	)
	require.NoError(t, err)

	// Clean up the container after the test
	defer func() {
		if err := testcontainers.TerminateContainer(pgContainer); err != nil {
			t.Logf("failed to terminate container: %s", err)
		}
	}()

	// Grab connection string
	connStr, err := pgContainer.ConnectionString(ctx, "sslmode=disable")
	require.NoError(t, err)

	// 2. Initialize dbdiff Driver
	driver, err := db.NewDriver(connStr)
	require.NoError(t, err)

	err = driver.Connect(ctx, connStr, "disable", 5*time.Second)
	require.NoError(t, err)
	defer driver.Close()

	// 3. Setup dummy schema
	setupSQL := `
	CREATE TABLE users (
		id SERIAL PRIMARY KEY,
		username VARCHAR(50) NOT NULL,
		email VARCHAR(255) UNIQUE NOT NULL,
		created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
	);

	CREATE INDEX idx_users_username ON users(username);
	`
	err = driver.Exec(ctx, setupSQL)
	require.NoError(t, err)

	// 4. Test Introspection
	schemaObj, err := driver.Introspect(ctx, "public", []string{})
	require.NoError(t, err)

	// 5. Verify parsed schema
	assert.NotNil(t, schemaObj)

	// Verify "users" table
	var usersTable *types.Table
	for i := range schemaObj.Tables {
		if schemaObj.Tables[i].Name == "users" {
			usersTable = &schemaObj.Tables[i]
			break
		}
	}
	require.NotNil(t, usersTable, "Expected 'users' table to be found in introspected schema.")
	assert.Equal(t, "users", usersTable.Name)

	// Verify "users" columns
	columnNames := []string{}
	for _, c := range usersTable.Columns {
		columnNames = append(columnNames, c.Name)
	}
	assert.Contains(t, columnNames, "id")
	assert.Contains(t, columnNames, "username")
	assert.Contains(t, columnNames, "email")
	assert.Contains(t, columnNames, "created_at")

	// Verify "users" indices
	assert.True(t, len(usersTable.Indexes) > 0, "Expected generated indexes on 'users' table")

	hasUsernameIdx := false
	for _, idx := range usersTable.Indexes {
		if idx.Name == "idx_users_username" {
			hasUsernameIdx = true
		}
	}
	assert.True(t, hasUsernameIdx, "Expected idx_users_username to exist")

	// 6. Generated index DDL runs on the server and recreates the index exactly
	testhelper.RoundTripIndex(ctx, t, driver, "public", "users", "idx_users_username")

	// 7. The migration dbdiff generates from one database to another runs there and
	// leaves no differences.
	require.NoError(t, driver.Exec(ctx, "CREATE DATABASE src"))
	require.NoError(t, driver.Exec(ctx, "CREATE DATABASE tgt"))
	connect := func(name string) db.Driver {
		url := strings.Replace(connStr, "/testdb?", "/"+name+"?", 1)
		d, err := db.NewDriver(url)
		require.NoError(t, err)
		require.NoError(t, d.Connect(ctx, url, "disable", 5*time.Second))
		t.Cleanup(d.Close)
		return d
	}
	testhelper.RequireMigrationRoundTrip(ctx, t, connect("src"), connect("tgt"), pgSource, pgTarget)
}

// pgSource and pgTarget differ by:
//   - a new table with an identity column, a check constraint and defaults;
//   - a new table (serial key) whose foreign key points at an existing table, with a plain
//     and a partial expression index;
//   - a unique constraint added (its index belongs to the constraint), an index that becomes
//     unique, and a check constraint whose expression changes on a column that widens;
//   - a column that gains NOT NULL under an index whose columns change, one widened to
//     bigint, one added with a default, and an indexed column dropped;
//   - a column, its foreign key and the table it points at dropped, and a dropped table;
//   - a new enum type a new table uses, a type change whose old default doesn't cast to the
//     new type, and a function dropped with the type its signature uses;
//   - an identity column widened to bigint (it has no default to drop).
const pgSource = `
	CREATE TYPE team_kind AS ENUM ('club', 'company');
	CREATE TABLE teams (
		id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		name varchar(100) NOT NULL,
		kind team_kind DEFAULT 'club',
		status varchar(20) DEFAULT 'active',
		created_at timestamptz DEFAULT now(),
		CONSTRAINT chk_teams_status CHECK (status <> '')
	);
	CREATE TABLE users (
		id serial PRIMARY KEY,
		email varchar(255) NOT NULL,
		name varchar(100) NOT NULL,
		handle varchar(50),
		code integer DEFAULT 0,
		age bigint,
		nickname varchar(50) DEFAULT 'none',
		CONSTRAINT uq_users_email UNIQUE (email),
		CONSTRAINT chk_users_age CHECK (age >= 18)
	);
	CREATE INDEX idx_users_name ON users (name, email);
	CREATE UNIQUE INDEX idx_users_handle ON users (handle);
	CREATE TABLE posts (
		id serial PRIMARY KEY,
		user_id integer NOT NULL,
		title varchar(200) NOT NULL,
		CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
	);
	CREATE INDEX idx_posts_user ON posts (user_id);
	CREATE INDEX idx_posts_title ON posts (lower(title)) WHERE title <> '';
	CREATE TABLE events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);`

const pgTarget = `
	CREATE TYPE mood AS ENUM ('happy', 'sad');
	CREATE FUNCTION cheer(m mood) RETURNS text AS $$ SELECT 'yay'::text $$ LANGUAGE sql;
	CREATE TABLE legacy_teams (id integer PRIMARY KEY);
	CREATE TABLE users (
		id serial PRIMARY KEY,
		email varchar(255) NOT NULL,
		name varchar(100),
		handle varchar(50),
		code varchar(10) DEFAULT 'x',
		age integer,
		legacy varchar(10) DEFAULT 'x',
		legacy_team_id integer,
		CONSTRAINT chk_users_age CHECK (age >= 0),
		CONSTRAINT fk_users_legacy_team FOREIGN KEY (legacy_team_id) REFERENCES legacy_teams (id)
	);
	CREATE INDEX idx_users_name ON users (name);
	CREATE INDEX idx_users_handle ON users (handle);
	CREATE INDEX idx_users_legacy ON users (legacy);
	CREATE TABLE audit (id integer PRIMARY KEY);
	CREATE TABLE events (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);`
