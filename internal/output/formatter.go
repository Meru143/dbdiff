package output

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/meru143/dbdiff/internal/db/dsn"
	dbdiff "github.com/meru143/dbdiff/internal/diff"
	"github.com/meru143/dbdiff/pkg/types"
)

// Format options
type FormatOptions struct {
	Format       string
	PrettyPrint  bool
	IncludeMeta  bool
	SourceDB     string // shown in the output's metadata, password hidden
	TargetDB     string // shown in the output's metadata, password hidden
	UseColors    bool
	IsExecutable bool // Add Executable output property

	// SQL output. Dialect is the target database's (postgresql, mysql, sqlserver; empty
	// means postgresql), Schema qualifies the statements' object names, and SourceSchema
	// supplies the definitions CREATE and ADD statements need.
	Dialect      string
	Schema       string
	SourceSchema *types.Schema
}

// Formatter handles output formatting
type Formatter struct {
	options FormatOptions
}

// NewFormatter creates a new formatter
func NewFormatter(format string) *Formatter {
	return &Formatter{
		options: FormatOptions{
			Format:      format,
			PrettyPrint: true,
			IncludeMeta: true,
			UseColors:   isTTY(),
		},
	}
}

// NewFormatterWithOptions creates a formatter with custom options
func NewFormatterWithOptions(opts FormatOptions) *Formatter {
	opts.UseColors = opts.UseColors && isTTY()
	return &Formatter{options: opts}
}

// Format formats diffs based on configured format
func (f *Formatter) Format(diffs types.DiffList) (string, error) {
	switch f.options.Format {
	case "sql":
		if f.options.IsExecutable {
			return f.FormatMigration(diffs, true)
		}
		return f.formatSQL(diffs, false), nil
	case "table":
		return f.formatTable(diffs), nil
	case "json":
		return f.formatJSON(diffs), nil
	default:
		return f.formatSQL(diffs, false), nil
	}
}

// FormatMigration formats diffs as migration SQL, wrapped in the dialect's transaction
// statements when transaction is set.
func (f *Formatter) FormatMigration(diffs types.DiffList, transaction bool) (string, error) {
	if f.options.IsExecutable {
		if f.options.Dialect != "" && f.options.Dialect != "postgresql" {
			return "", fmt.Errorf("--executable writes a psql script, which only works with PostgreSQL; the target is %s", f.options.Dialect)
		}
		return f.formatExecutable(diffs), nil
	}

	sql := f.formatSQL(diffs, transaction)
	if transaction {
		sql = dbdiff.WrapTransaction(f.options.Dialect, sql)
	}
	return sql, nil
}

// formatSQL generates the migration statements, in dependency order, under a metadata header.
// inTransaction reports whether the caller wraps the result in a transaction.
func (f *Formatter) formatSQL(diffs types.DiffList, inTransaction bool) string {
	var sb strings.Builder

	// Header comments
	if f.options.IncludeMeta {
		sb.WriteString("-- Generated by dbdiff\n")
		fmt.Fprintf(&sb, "-- Timestamp: %s\n", time.Now().Format("2006-01-02 15:04:05"))
		if f.options.SourceDB != "" {
			fmt.Fprintf(&sb, "-- Source: %s\n", dsn.Redact(f.options.SourceDB))
		}
		if f.options.TargetDB != "" {
			fmt.Fprintf(&sb, "-- Target: %s\n", dsn.Redact(f.options.TargetDB))
		}
		sb.WriteString("\n")
	}

	// The generator's own transaction wrapper is off since the caller handles that, and with
	// it PostgreSQL's CONCURRENTLY, which cannot run inside a transaction block.
	generator := dbdiff.NewSQLGeneratorWithSchema(diffs, f.options.Schema, f.options.SourceSchema, f.options.Dialect)
	generator.SetTransaction(false)
	generator.SetConcurrently(!inTransaction)
	sb.WriteString(generator.Generate())
	sb.WriteString("\n")

	return sb.String()
}

// formatExecutable generates an executable bash script wrapping the configured SQL
func (f *Formatter) formatExecutable(diffs types.DiffList) string {
	var sb strings.Builder

	// Write Bash shebang and error handling
	sb.WriteString("#!/bin/bash\n")
	sb.WriteString("set -e\n\n")

	sb.WriteString("# Generated by dbdiff\n")
	fmt.Fprintf(&sb, "# Timestamp: %s\n", time.Now().Format("2006-01-02 15:04:05"))
	sb.WriteString("# This script will execute the migrations natively using psql.\n\n")

	sb.WriteString("DB_URL=${1:-$DATABASE_URL}\n")
	sb.WriteString("if [ -z \"$DB_URL\" ]; then\n")
	sb.WriteString("  echo \"Error: DATABASE_URL environment variable or argument is required.\"\n")
	sb.WriteString("  echo \"Usage: $0 [postgres://user:pass@host:port/db]\"\n")
	sb.WriteString("  exit 1\n")
	sb.WriteString("fi\n\n")

	sb.WriteString("echo \"Validating database connection...\"\n")
	sb.WriteString("if ! psql \"$DB_URL\" -c '\\q' >/dev/null 2>&1; then\n")
	// The URL stays out of the message: it holds the password, and the script's output
	// often lands in CI logs.
	sb.WriteString("  echo \"Error: Unable to connect to the database\"\n")
	sb.WriteString("  exit 1\n")
	sb.WriteString("fi\n\n")

	sb.WriteString("echo \"Applying migrations...\"\n")
	sb.WriteString("psql -v ON_ERROR_STOP=1 \"$DB_URL\" << 'EOF'\n")
	sb.WriteString("BEGIN;\n\n")

	// Embed the entire raw SQL inside the hermetic bash wrapper
	sql := f.formatSQL(diffs, true)
	sb.WriteString(sql)

	sb.WriteString("\nCOMMIT;\n")
	sb.WriteString("EOF\n\n")

	sb.WriteString("echo \"Migrations completed successfully!\"\n")

	return sb.String()
}

// formatTable creates ASCII table output
func (f *Formatter) formatTable(diffs types.DiffList) string {
	var sb strings.Builder

	// Color codes
	green := "\033[32m"
	red := "\033[31m"
	yellow := "\033[33m"
	reset := "\033[0m"

	// Header
	sb.WriteString("\n")
	sb.WriteString("┌──────┬──────────┬──────────────┬───────────────┬────────────────────────────┐\n")
	sb.WriteString("│ Type │ Object   │ Name         │ Table         │ Details                    │\n")
	sb.WriteString("├──────┼──────────┼──────────────┼───────────────┼────────────────────────────┤\n")

	for _, diff := range diffs {
		details := ""
		if diff.OldValue != "" && diff.NewValue != "" {
			details = fmt.Sprintf("%s → %s", diff.OldValue, diff.NewValue)
		}

		typeStr := string(diff.Type)
		objStr := string(diff.Object)

		// Apply colors if enabled
		if f.options.UseColors {
			switch diff.Type {
			case types.DiffAdd:
				typeStr = green + typeStr + reset
			case types.DiffDrop:
				typeStr = red + typeStr + reset
			case types.DiffAlter:
				typeStr = yellow + typeStr + reset
			}
		}

		fmt.Fprintf(&sb, "│ %-4s │ %-8s │ %-12s │ %-13s │ %-26s │\n",
			typeStr,
			objStr,
			truncate(diff.Name, 12),
			truncate(diff.TableName, 13),
			truncate(details, 26),
		)
	}
	sb.WriteString("└──────┴──────────┴──────────────┴───────────────┴────────────────────────────┘\n")

	return sb.String()
}

// formatJSON creates JSON output
func (f *Formatter) formatJSON(diffs types.DiffList) string {
	if diffs == nil {
		diffs = types.DiffList{} // [], not null, when nothing differs
	}
	var output interface{}

	if f.options.IncludeMeta {
		// Wrap with metadata
		output = map[string]interface{}{
			"metadata": map[string]string{
				"timestamp":   time.Now().Format(time.RFC3339),
				"generatedBy": "dbdiff",
				"source":      dsn.Redact(f.options.SourceDB),
				"target":      dsn.Redact(f.options.TargetDB),
			},
			"diffs": diffs,
		}
	} else {
		output = diffs
	}

	var bytes []byte
	var err error
	if f.options.PrettyPrint {
		bytes, err = json.MarshalIndent(output, "", "  ")
	} else {
		bytes, err = json.Marshal(output)
	}

	if err != nil {
		return fmt.Sprintf(`{"error": "%v"}`, err)
	}

	return string(bytes)
}

// WriteFile writes content to a file
func WriteFile(path string, content string) error {
	// Create parent directories if needed
	if idx := strings.LastIndex(path, "/"); idx > 0 {
		dir := path[:idx]
		if err := os.MkdirAll(dir, 0755); err != nil {
			return fmt.Errorf("failed to create directory: %w", err)
		}
	}

	// A text file ends with a newline; a migration used to end with "COMMIT;".
	if content != "" && !strings.HasSuffix(content, "\n") {
		content += "\n"
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write file: %w", err)
	}
	return nil
}

// isTTY checks if stdout is a terminal
func isTTY() bool {
	fi, err := os.Stdout.Stat()
	if err != nil {
		return false
	}
	return (fi.Mode() & os.ModeCharDevice) != 0
}

func truncate(s string, maxLen int) string {
	if len(s) > maxLen {
		return s[:maxLen-2] + ".."
	}
	if s == "" {
		return "-"
	}
	return s
}
